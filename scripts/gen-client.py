"""Generate a typed client from docs/openapi.json.

    python scripts/gen-client.py            # writes src/localai_gateway/client.py
    python scripts/gen-client.py --check    # fails if the file is stale (CI gate)

The mapping is deliberately explicit instead of clever: the API is frozen, and a generator that
guesses would produce a client nobody trusts. Unknown paths make the generator fail loudly.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs" / "openapi.json"
OUT = ROOT / "src" / "localai_gateway" / "client.py"

# path -> (python method name, kind)
ROUTES: dict[str, tuple[str, str]] = {
    "/healthz": ("healthz", "get"),
    "/doctor": ("doctor", "get"),
    "/v1/models": ("models", "get"),
    "/v1/chat/completions": ("chat", "post"),
    "/v1/bench": ("bench", "post"),
    "/v1/placement": ("placement", "get"),
    "/v1/autotune": ("autotune", "get"),
    "/v1/rsi/sessions": ("rsi_start", "post"),
    "/v1/rsi/events": ("rsi_event", "post"),
    "/v1/rsi/finalize": ("rsi_finalize", "post"),
    "/v1/rsi/pairs": ("rsi_pairs", "get"),
    "/v1/rsi/stats": ("rsi_stats", "get"),
}

SIGNATURES: dict[str, str] = {
    "healthz": "",
    "doctor": "",
    "models": "",
    "chat": "body: dict",
    "bench": "body: dict",
    "placement": "budget_mb: int | None = None, kinds: str = \"llm\", pinned: str = \"\"",
    "autotune": "model: str, ctx: int = 16384",
    "rsi_start": "session: str",
    "rsi_event": "event: dict",
    "rsi_finalize": "session: str",
    "rsi_pairs": "session: str",
    "rsi_stats": "",
}

HEADER = '''"""Typed client for the LocalAI Gateway API.

GENERATED by scripts/gen-client.py from docs/openapi.json - do not edit by hand.
Run `python scripts/gen-client.py` after changing a route; CI fails if this file is stale.
"""
from __future__ import annotations

from typing import Any

import httpx


class GatewayError(RuntimeError):
    """The gateway answered with an error envelope: {"error": {"code", "reason"}}."""

    def __init__(self, status: int, code: str, reason: str, payload: dict | None = None) -> None:
        super().__init__(f"{status} {code}: {reason}")
        self.status, self.code, self.reason, self.payload = status, code, reason, payload or {}


class GatewayClient:
    """Thin, explicit wrapper around the frozen API surface."""

    def __init__(self, base_url: str = "http://127.0.0.1:8090", *, timeout: float = 600.0,
                 client: httpx.Client | None = None) -> None:
        self.base_url = base_url.rstrip("/")
        self._client = client or httpx.Client(timeout=timeout)

    def close(self) -> None:
        self._client.close()

    def __enter__(self) -> "GatewayClient":
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()

    def _request(self, method: str, path: str, **kwargs: Any) -> Any:
        response = self._client.request(method, f"{self.base_url}{path}", **kwargs)
        try:
            payload = response.json()
        except ValueError:
            payload = None
        if response.status_code >= 400:
            error = (payload or {}).get("error", {}) if isinstance(payload, dict) else {}
            raise GatewayError(response.status_code, error.get("code", "http_error"),
                               error.get("reason", response.text[:200]), payload)
        return payload
'''


def render(spec: dict) -> str:
    paths = set(spec["paths"])
    missing = paths - set(ROUTES)
    if missing:
        raise SystemExit(
            "openapi has paths the client generator does not know: "
            + ", ".join(sorted(missing))
            + "\nadd them to ROUTES/SIGNATURES in scripts/gen-client.py"
        )
    lines = [HEADER]
    for path in sorted(ROUTES):
        if path not in paths:
            raise SystemExit(f"ROUTES lists {path}, but openapi does not")
        name, kind = ROUTES[path]
        sig = SIGNATURES.get(name, "")
        args = f", {sig}" if sig else ""
        lines.append(f"\n    def {name}(self{args}) -> Any:")
        doc = spec["paths"][path][kind].get("summary") or spec["paths"][path][kind].get("operationId", name)
        lines.append(f'        """{doc} ({kind.upper()} {path})."""')
        if kind == "get":
            if sig:
                pairs = []
                for chunk in sig.split(", "):
                    param = chunk.split(":")[0].split("=")[0].strip()
                    pairs.append(f'"{param}": {param}')
                lines.append(f"        params = {{{', '.join(pairs)}}}")
                lines.append(f'        return self._request("GET", "{path}", params={{k: v for k, v in params.items() if v not in (None, "")}})')
            else:
                lines.append(f'        return self._request("GET", "{path}")')
        else:
            if name in ("rsi_start",):
                lines.append(f'        return self._request("POST", "{path}", json={{"session": session}})')
            elif name in ("rsi_finalize",):
                lines.append(f'        return self._request("POST", "{path}", json={{"session": session}})')
            elif name == "rsi_event":
                lines.append(f'        return self._request("POST", "{path}", json=event)')
            else:
                lines.append(f'        return self._request("POST", "{path}", json=body)')
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Generate the typed gateway client from the OpenAPI snapshot")
    p.add_argument("--check", action="store_true", help="fail if client.py is stale")
    args = p.parse_args(argv)

    spec = json.loads(SPEC.read_text(encoding="utf8"))
    code = render(spec)
    if args.check:
        current = OUT.read_text(encoding="utf8") if OUT.exists() else ""
        if current != code:
            print("client.py is stale - run: python scripts/gen-client.py")
            return 1
        print("client.py is up to date")
        return 0
    OUT.write_text(code, encoding="utf8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(code.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
